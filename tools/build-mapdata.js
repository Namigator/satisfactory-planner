// Builds js/mapdata.js (resource node positions) and downloads the world map source image
// (img/map.avif) from the community map project https://github.com/Tjark-Kuehl/satisfactorymap.
// Then run `python tools/build-maptiles.py` to cut it into the tiles the page actually loads.
// Usage: node tools/build-mapdata.js [path-to-resources.json]
const fs = require('fs');
const path = require('path');

const REPO = 'https://raw.githubusercontent.com/Tjark-Kuehl/satisfactorymap/main/';
const ROOT = path.join(__dirname, '..');

// World extents covered by the map image, in game units (cm). Y grows southward.
const BOUNDS = { x0: -324698.832, x1: 425301.168, y0: -375000, y1: 375000 };
const PURITY = { impure: 0, normal: 1, pure: 2 };
const ITEM_ALIASES = { Desc_LiquidOilWell_C: 'Desc_LiquidOil_C' };

async function get(url, binary) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed (${res.status}): ${url}`);
  return binary ? Buffer.from(await res.arrayBuffer()) : res.json();
}

(async () => {
  const src = process.argv[2] ? JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) : await get(REPO + 'resources.json');

  // Node kinds: 'node' = miner / oil extractor node, 'well' = resource well satellite (fracking),
  // 'geyser' = site for a geothermal generator.
  const nodes = [];
  for (const tab of src.options) {
    const kind = { resource_nodes: 'node', resource_wells: 'well' }[tab.tabId];
    if (!kind) continue;
    for (const group of tab.options) {
      const item = ITEM_ALIASES[group.type] || group.type;
      const nodeKind = item === 'Desc_Geyser_C' ? 'geyser' : kind;
      for (const layer of group.options) {
        for (const m of layer.markers || []) {
          const id = m.pathName.split('.').pop();
          const node = [id, item, PURITY[m.purity], Math.round(m.x) / 100, Math.round(m.y) / 100, nodeKind];
          if (m.core) node.push(m.core.split('.').pop());
          nodes.push(node);
        }
      }
    }
  }

  const b = BOUNDS;
  const out =
    '// Generated by tools/build-mapdata.js from Tjark-Kuehl/satisfactorymap. Do not edit.\n' +
    '// Coordinates are in meters (game units / 100). node = [id, item, purity 0-2, x, y, kind, wellCore?]\n' +
    `window.SF_MAP = ${JSON.stringify({
      bounds: { x0: b.x0 / 100, x1: b.x1 / 100, y0: b.y0 / 100, y1: b.y1 / 100 },
      nodes,
    })};\n`;
  fs.writeFileSync(path.join(ROOT, 'js', 'mapdata.js'), out);

  const img = path.join(ROOT, 'img', 'map.avif');
  if (!fs.existsSync(img)) {
    fs.mkdirSync(path.dirname(img), { recursive: true });
    fs.writeFileSync(img, await get(REPO + 'public/assets/Map-HQ.avif', true));
  }
  console.log(`Wrote js/mapdata.js: ${nodes.length} nodes`);
})();
